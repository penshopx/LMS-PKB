function progressionIndicators(
  subject: string,
  application: string,
  governance: string,
): BehaviorIndicator[] {
  return [
    {
      level: "L1",
      indicators: [
        `Memahami tujuan dan ruang lingkup ${subject}`,
        `Mengenali dokumen dan pihak yang terkait dengan ${subject}`,
      ],
    },
    {
      level: "L2",
      indicators: [
        `Menerapkan ${application} sesuai prosedur perusahaan`,
        `Menyiapkan evidensi penerapan ${subject}`,
      ],
    },
    {
      level: "L3",
      indicators: [
        `Menilai kesesuaian dan risiko dalam ${subject}`,
        `Menangani ketidaksesuaian serta menyusun tindak lanjut`,
      ],
    },
    {
      level: "L4",
      indicators: [
        `Menetapkan ${governance} untuk ${subject}`,
        `Membina tim dan mengevaluasi peningkatan berkelanjutan`,
      ],
    },
  ];
}

function courseLessons(
  key: string,
  subject: string,
  context: string,
  reference: string,
  practice: string,
): Lesson[] {
  return [
    {
      id: `${key}-orientation`,
      order: 1,
      type: "orientation",
      title: "Orientasi Kompetensi",
      description: `Memahami standar kompetensi ${subject}`,
      content: `Tujuan, ruang lingkup, peran, dan evidensi kompetensi ${subject}.`,
    },
    {
      id: `${key}-context`,
      order: 2,
      type: "context",
      title: "Konteks Usaha Konstruksi",
      description: context,
      content: "Studi kasus badan usaha dan pekerjaan konstruksi; LKUT digunakan hanya sebagai konteks kebutuhan pembelajaran.",
    },
    {
      id: `${key}-microlearning`,
      order: 3,
      type: "microlearning",
      title: "Regulasi dan Praktik Utama",
      description: reference,
      content: "Ringkasan regulasi, checklist penerapan, dan contoh evidensi yang relevan.",
      references: baselineLessonReferences(key.replace(/(\D)(\d)/, "$1-$2")),
    },
    {
      id: `${key}-practice`,
      order: 4,
      type: "practice",
      title: "Praktik Berbasis Pekerjaan",
      description: practice,
      content: "Tugas praktik menggunakan skenario usaha atau proyek konstruksi tanpa menyusun LKUT di dalam LMS.",
    },
    {
      id: `${key}-assessment`,
      order: 5,
      type: "assessment",
      title: "Asesmen Kompetensi",
      description: `Mengukur penerapan ${subject}`,
      content: "Pre-test/post-test, penilaian studi kasus, dan unggah evidensi penerapan.",
    },
    {
      id: `${key}-reflection`,
      order: 6,
      type: "reflection",
      title: "Refleksi dan Rencana Tindak Lanjut",
      description: "Membandingkan kondisi sebelum dan sesudah pembelajaran",
      content: "Refleksi hasil belajar dan rencana perbaikan yang dapat diterapkan pada badan usaha atau proyek.",
    },
  ];
}

